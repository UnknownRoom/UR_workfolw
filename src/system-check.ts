import { execFile } from 'child_process';
import { readFile, writeFile } from 'fs/promises';
import * as os from 'os';
import * as path from 'path';
import { promisify } from 'util';

const execFileAsync = promisify(execFile);

export type OperatingSystem = 'macOS' | 'Windows' | 'Linux' | 'other';
export type CpuArchitecture = 'arm' | 'x86' | 'other';

export interface ExecutableCheck {
  installed: boolean;
  command: string | null;
  version: string | null;
}

export interface SystemCheckResult {
  operatingSystem: OperatingSystem;
  platform: string;
  architecture: CpuArchitecture;
  arch: string;
  python: ExecutableCheck;
  git: ExecutableCheck;
  checkedAt: string;
}

export function getSystemCheckFilePath(outputDirectory = __dirname): string {
  return path.join(outputDirectory, 'system-check.json');
}

/** Reads the JSON report generated by checkSystem. */
export async function readSystemCheck(outputDirectory = __dirname): Promise<SystemCheckResult> {
  const contents = await readFile(getSystemCheckFilePath(outputDirectory), 'utf8');
  return JSON.parse(contents) as SystemCheckResult;
}

interface CommandCandidate {
  command: string;
  args: string[];
}

function getOperatingSystem(platform: NodeJS.Platform): OperatingSystem {
  switch (platform) {
    case 'darwin': return 'macOS';
    case 'win32': return 'Windows';
    case 'linux': return 'Linux';
    default: return 'other';
  }
}

function getArchitecture(arch: string): CpuArchitecture {
  if (/^(arm|arm64|aarch64)$/i.test(arch)) return 'arm';
  if (/^(x86|ia32|x64|amd64)$/i.test(arch)) return 'x86';
  return 'other';
}

async function inspectExecutable(candidates: CommandCandidate[]): Promise<ExecutableCheck> {
  for (const candidate of candidates) {
    try {
      const { stdout, stderr } = await execFileAsync(candidate.command, candidate.args, {
        timeout: 5000,
        windowsHide: true,
        maxBuffer: 1024 * 1024
      });
      const version = `${stdout}\n${stderr}`.trim().split(/\r?\n/).find((line) => line.trim())?.trim();
      return {
        installed: true,
        command: [candidate.command, ...candidate.args].join(' '),
        version: version ?? 'version unknown'
      };
    } catch (error) {
      const code = (error as NodeJS.ErrnoException).code;
      // A missing executable means we should try the next common command name.
      if (code === 'ENOENT') continue;
      // A program that exists but failed to report its version is still present.
      if (code !== 'ETIMEDOUT') {
        const result = error as Error & { stdout?: string; stderr?: string };
        const version = `${result.stdout ?? ''}\n${result.stderr ?? ''}`.trim()
          .split(/\r?\n/).find((line) => line.trim())?.trim();
        return {
          installed: true,
          command: [candidate.command, ...candidate.args].join(' '),
          version: version ?? 'version unavailable'
        };
      }
      return {
        installed: true,
        command: [candidate.command, ...candidate.args].join(' '),
        version: 'version check timed out'
      };
    }
  }

  return { installed: false, command: null, version: null };
}

/** Detects the host system and writes system-check.json beside the running module. */
export async function checkSystem(outputDirectory = __dirname): Promise<SystemCheckResult> {
  const pythonCandidates: CommandCandidate[] = process.platform === 'win32'
    ? [
        { command: 'py', args: ['-3', '--version'] },
        { command: 'python', args: ['--version'] },
        { command: 'python3', args: ['--version'] }
      ]
    : [
        { command: 'python3', args: ['--version'] },
        { command: 'python', args: ['--version'] }
      ];

  const [python, git] = await Promise.all([
    inspectExecutable(pythonCandidates),
    inspectExecutable([{ command: 'git', args: ['--version'] }])
  ]);

  const result: SystemCheckResult = {
    operatingSystem: getOperatingSystem(process.platform),
    platform: process.platform,
    architecture: getArchitecture(os.arch()),
    arch: os.arch(),
    python,
    git,
    checkedAt: new Date().toISOString()
  };

  const outputPath = getSystemCheckFilePath(outputDirectory);
  await writeFile(outputPath, `${JSON.stringify(result, null, 2)}\n`, 'utf8');
  return result;
}
